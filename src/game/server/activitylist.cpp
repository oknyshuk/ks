/// Add a deferred response.
void CResponseQueue::Add( const AIConcept_t &conc,  ///< concept to dispatch
		 const AI_CriteriaSet * __restrict__ contexts,
		 float time,					 ///< when to dispatch it. You can specify a time of zero to mean "immediately."
		 const CFollowupTargetSpec_t &targetspec,
		 CBaseEntity *pIssuer
		 )
{
	// Add a response.
	contract_assert( ( (int)m_Queue.size() < AI_RESPONSE_QUEUE_SIZE ) && "AI Response queue overfilled." );
	m_Queue.emplace_back().Init( conc, contexts, time, targetspec, pIssuer );
}

/// Remove a deferred response matching the concept and issuer.
void CResponseQueue::Remove( const AIConcept_t &conc,  ///< concept to dispatch
			CBaseEntity * const __restrict__ pIssuer		  ///< the entity issuing the response, if one exists.
			) __restrict__
{
	// walk through the queue until we find a response matching the concept and issuer, then strike it.
	QueueType_t::iterator idx = m_Queue.begin();
	while (idx != m_Queue.end())
	{
		CDeferredResponse &response = *idx;
		QueueType_t::iterator previdx = idx; // advance the index immediately because we may be deleting the "current" element
		idx = std::next(idx); // is now the next index
		if ( CompareConcepts( response.m_concept, conc ) && // if concepts match and
			( !pIssuer || ( response.m_hIssuer.Get() == pIssuer ) ) // issuer is null, or matches the one in the response
			)
		{
			m_Queue.erase(previdx);
		}
	}
}

void CResponseQueue::RemoveSpeechQueuedFor( const CBaseEntity *pSpeaker )
{
	// walk through the queue until we find a response matching the speaker, then strike it.
	// because responses are dispatched from inside a loop that is already walking through the
	// queue, it's not safe to actually remove the elements. Instead, quash it by replacing it
	// with a null event.
	
	for ( QueueType_t::iterator idx = m_Queue.begin() ;
		  idx != m_Queue.end() ;
		  idx = std::next(idx) ) // is now the next index
	{
		CDeferredResponse &response = *idx;
		if ( response.m_Target.m_hHandle.Get() == pSpeaker )
		{
			response.Quash();
		}
	}
}

