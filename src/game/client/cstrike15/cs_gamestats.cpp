//-----------------------------------------------------------------------------
ShadowType_t CHostageCarriableProp::ShadowCastType()
{
	if ( IsEffectActive( /*EF_NODRAW |*/ EF_NOSHADOW ) )
		return SHADOWS_NONE;

	if ( ShouldDraw() )
		return SHADOWS_RENDER_TO_TEXTURE;

	return SHADOWS_NONE;
}

//-----------------------------------------------------------------------------
// Purpose: Returns whether object should render.
//-----------------------------------------------------------------------------
bool CHostageCarriableProp::ShouldDraw( void )
{
	CBaseEntity *pOwner = GetFollowedEntity();

	// weapon has no owner, don't draw it - will get removed soon
	if ( !pOwner )
		return false;

	CBasePlayer *pViewedPlayer = GetLocalOrInEyeCSPlayer();
	CCSPlayer *pLocalPlayer = CCSPlayer::GetLocalCSPlayer();

	// carried by local player?
	if ( pOwner == pViewedPlayer )
	{
		if ( pLocalPlayer->GetObserverMode() == OBS_MODE_IN_EYE )
			return false;

		// 3rd person mode
		return pViewedPlayer->ShouldDrawLocalPlayer();
	}

	return BaseClass::ShouldDraw();
}

void CHostageCarriableProp::ClientThink()
{
	BaseClass::ClientThink();

	int a = GetRenderAlpha();

	if ( m_flFadeInStartTime + 1.0 > gpGlobals->curtime )
	{
		SetRenderMode( kRenderGlow );
		a = ((gpGlobals->curtime - m_flFadeInStartTime) /  1.0f) * 255;
	}
	else
	{
		SetRenderMode( kRenderNormal );
		a = 255;
	}

	a = std::max( 0, a );
	SetRenderAlpha( a );
}

